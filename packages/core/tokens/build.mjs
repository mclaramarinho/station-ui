import StyleDictionary from 'style-dictionary';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const directory = dirname(fileURLToPath(import.meta.url));

function colorLiteral(value) {
  const hex = /^#?([\da-f]{3}|[\da-f]{6}|[\da-f]{8})$/i.exec(value)?.[1];
  if (hex) {
    const expanded = hex.length === 3 ? [...hex].map((digit) => digit + digit).join('') : hex;
    const rgb = expanded.slice(0, 6);
    const alpha = expanded.length === 8 ? expanded.slice(6) : 'FF';
    return `0x${alpha}${rgb}`.toUpperCase();
  }

  const rgba = /^rgba?\(\s*(\d+(?:\.\d+)?)\s*,\s*(\d+(?:\.\d+)?)\s*,\s*(\d+(?:\.\d+)?)(?:\s*,\s*(\d*\.?\d+))?\s*\)$/i.exec(
    value,
  );
  if (!rgba) return undefined;

  const channels = rgba.slice(1, 4).map((channel) => Number(channel));
  const alpha = rgba[4] === undefined ? 255 : Math.round(Number(rgba[4]) * 255);
  const bytes = [...channels, alpha].map((channel) =>
    Math.max(0, Math.min(255, Math.round(channel)))
      .toString(16)
      .padStart(2, '0'),
  );
  return `0x${bytes[3]}${bytes[0]}${bytes[1]}${bytes[2]}`.toUpperCase();
}

function dartLiteral(token) {
  const value = token.original.$value ?? token.original.value;
  if (typeof value !== 'string') return JSON.stringify(value);

  const color = colorLiteral(value);
  if (color && token.path.join('-').toLowerCase().includes('color')) return color;

  const percentage = /^(-?\d+(?:\.\d+)?)%$/.exec(value);
  if (percentage) return String(Number(percentage[1]) / 100);

  const pixelValue = /^(-?\d+(?:\.\d+)?)px$/i.exec(value);
  if (pixelValue) {
    const number = Number(pixelValue[1]);
    return Number.isInteger(number) ? `${number}.0` : String(number);
  }

  if (/^-?\d+(?:\.\d+)?$/.test(value)) return value;
  return JSON.stringify(value);
}

StyleDictionary.registerFormat({
  name: 'station/dart-class',
  format: ({ dictionary, options }) => {
    const className = options.className ?? 'StationTokens';
    const properties = dictionary.allTokens
      .map((token) => `  static const ${token.name} = ${dartLiteral(token)};`)
      .join('\n');

    return [
      '// Generated by Style Dictionary. Do not edit directly.',
      '',
      `class ${className} {`,
      `  ${className}._();`,
      '',
      properties,
      '}',
      '',
    ].join('\n');
  },
});

const dictionary = new StyleDictionary(resolve(directory, 'config.json'));
await dictionary.buildAllPlatforms();
